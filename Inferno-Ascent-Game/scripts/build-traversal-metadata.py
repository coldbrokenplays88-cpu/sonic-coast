"""Map authored sprite components and pivots; never modify source image pixels."""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image
from scipy import ndimage

root = Path(__file__).resolve().parents[1]
frames, sources = {}, []
for key, filename, rows, scale in [
    ('traversalActing', 'sonic-traversal-acting.png', [0, 280, 532, 768], 60 / 230),
    ('traversalLaunch', 'sonic-traversal-launch.png', [0, 270, 442, 660, 887], 60 / 239),
]:
    path = root / 'assets' / filename
    pixels = np.array(Image.open(path).convert('RGBA'))
    labels, _ = ndimage.label(pixels[:, :, 3] > 128)
    areas = np.bincount(labels.ravel())
    components = []
    for label, region in enumerate(ndimage.find_objects(labels), 1):
        if region is None or areas[label] < 2000:
            continue
        y, x = region
        row = next(i for i in range(len(rows)-1) if rows[i] <= y.start < rows[i+1])
        components.append((row, x.start, y.start, x.stop, y.stop, label))
    components.sort()
    assert len(components) == (len(rows)-1)*8
    assert all(sum(c[0] == row for c in components) == 8 for row in range(len(rows)-1))
    result = []
    for row, left, top, right, bottom, label in components:
        # Foot pivots use the planted shoe, not the changing overall silhouette.
        strip = pixels[bottom-12:bottom, left:right].astype(float)
        red = (strip[:, :, 0] > 120) & (strip[:, :, 0] > strip[:, :, 1]*1.6) & (strip[:, :, 3] > 128)
        _, shoe_x = np.where(red)
        center = float(np.median(shoe_x)) if len(shoe_x) else (right-left)/2
        if key == 'traversalActing' and row < 2:
            # The first backwards pose has both shoes down; keep its rear support.
            if row == 1 and len(result) == 8:
                center = 78
            anchor = [center, bottom-top]
        elif key == 'traversalActing':
            # The collision wall is 14 world units ahead of the player's center.
            anchor = [right-left-14/scale, bottom-top]
        elif row == 0:
            anchor = [center, bottom-top]
        else:
            # Rotating airborne poses pivot around the body, not a changing foot.
            anchor = [(right-left)/2, (bottom-top)/2]
        frame = {'bounds': [left, top, right, bottom],
                 'anchor': [round(v) for v in anchor], 'scale': scale}
        # A few outstretched silhouettes overlap their neighbors' rectangular
        # atlas bounds. Exclude only those disconnected neighboring fragments
        # during extraction; do not erase or repaint any source pixels.
        trims = []
        region = labels[top:bottom, left:right]
        for other in np.unique(region):
            if other == 0 or other == label or areas[other] < 2000:
                continue
            yy, xx = np.where(region == other)
            x0, x1, y0, y1 = int(xx.min()), int(xx.max()+1), int(yy.min()), int(yy.max()+1)
            assert not np.any(region[y0:y1, x0:x1] == label), (filename, row, left)
            trims.append([x0, y0, x1-x0, y1-y0])
        if trims:
            frame['trim'] = trims
        result.append(frame)
    frames[key] = result
    sources.append({'file': 'assets/'+filename, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                    'size': [pixels.shape[1], pixels.shape[0]], 'frames': len(result)})
(root/'traversal-frames.js').write_text("'use strict';\n// Generated by scripts/build-traversal-metadata.py; source pixels remain untouched.\nconst traversalSpriteFrames=" + json.dumps(frames, separators=(',', ':')) + ';\n')
(root/'assets/traversal-art-metadata.json').write_text(json.dumps({'assets': sources,
    'reference': ['sonic-recovered-speedster.png', 'sonic-supplemental.png'],
    'acting': '8 forward balance, 8 backward balance, 8 pushing poses',
    'launch': '8 upright spring poses, 8 vent poses, 16 spiral grinding poses',
    'production': 'Generated with imagegen from the existing character artwork. Motion references guide poses only. Original sheets and generated source pixels are unchanged.'}, indent=2)+'\n')
print('Mapped 56 traversal frames; source pixels unchanged.')
